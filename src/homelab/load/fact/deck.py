decks = homelab.core.dataset.bronze.google_drive.decks.read_parquet()
cards = homelab.core.dataset.silver.scryfall.cards.read_parquet()
tags = homelab.core.dataset.silver.scryfall.oracle_tags.read_parquet()

deck_tagged = (
    decks.filter(pl.col("deck").eq(DECK))
    .join(other=cards, on="card", how="left")
    .join(other=tags, on="oracle_id", how="left")
)

tags_synergies = get_tag_synergy()
recommended = (
    deck_tagged.select("tag")
    .join(other=tags_synergies, left_on="tag", right_on="tag_a", how="left")
    .join(other=tags, left_on="tag_b", right_on="tag", how="left")
    .join(
        other=cards.filter(pl.col("color").eq("G")), on="oracle_id", how="left"
    )
    .get_column("card")
    .value_counts()
    .sort("count", descending=True)
    .to_pandas()
)
